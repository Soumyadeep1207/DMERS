"""Drive every database laboratory through the running API and print what PostgreSQL really did.

    python -m db.tools.lab_demo [--base http://localhost:5003] [--rows 200000] > docs/review3/dbms_lab_outputs.md

Needs the stack running in demo mode (DMERS_DEMO_MODE=1). It changes demo data only and puts it back:
the tampered timeline entry is restored, test incidents are created, and the Review II data is reset at the end.
Output is Markdown, every number comes from a response, nothing is typed in by hand.
"""
from __future__ import annotations

import argparse
import json
import threading
import time
import urllib.error
import urllib.request

PEOPLE = {"admin": "meena.krishnan@dmers.example.org", "coordinator": "priya.natarajan@dmers.example.org", "citizen": "gopal.iyer@mail.example.com"}
PASSWORD = "Dmers@2026"
FIRE_STATION, ASA_HOSPITAL = (12.914123, 79.131245), (12.937004, 79.162903)


class Client:
    def __init__(self, base: str, email: str):
        self.base, self.token = base, None
        self.token = self.call("POST", "/api/auth/login", {"email": email, "password": PASSWORD})[1]["token"]

    def call(self, method: str, path: str, body=None, timeout: int = 300):
        data = None if body is None else json.dumps(body).encode()
        request = urllib.request.Request(self.base + path, data=data, method=method, headers={"Content-Type": "application/json", **({"Authorization": f"Bearer {self.token}"} if self.token else {})})
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:
                return response.status, json.loads(response.read() or b"{}")
        except urllib.error.HTTPError as error:
            return error.code, json.loads(error.read() or b"{}")


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join("" if c is None else str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", default="http://localhost:5003")
    parser.add_argument("--rows", type=int, default=200000)
    args = parser.parse_args()
    admin, coordinator, citizen = (Client(args.base, PEOPLE[k]) for k in ("admin", "coordinator", "citizen"))
    R = "/api/response"
    print("# DMERS database laboratories: outputs from a real run\n")
    print(f"Generated by `python -m db.tools.lab_demo` against {args.base} on {time.strftime('%Y-%m-%d %H:%M')} (local time). Every value below is a response from the running system. The synthetic history has {args.rows:,} generated rows; it is not real incident data.\n")

    # ---- 1 hash chain
    print("## 1. Tamper-evident timeline (migration 005)\n")
    s, before = coordinator.call("GET", f"{R}/lab/chain")
    print(f"Verification before any attack: {before['entries_checked']} entries in {before['incidents_checked']} incidents, **{before['broken']} broken**.\n")
    _, entries = coordinator.call("GET", f"{R}/lab/chain/1")
    original = entries["entries"][1]["note"]
    s, edit = admin.call("POST", f"{R}/lab/chain/tamper", {"incident_id": 1, "update_no": 2, "note": "Nothing unusual happened."})
    print(f"Attack: `POST /lab/chain/tamper` (status {s}) rewrote the note of incident 1, entry 2 from \"{original}\" to \"Nothing unusual happened.\" with triggers bypassed. Triggers listed in the trace: {[c for c in edit['db_trace']['components'] if c.startswith('trigger')] or 'none'}.\n")
    _, after = coordinator.call("GET", f"{R}/lab/chain")
    bad = [i for i in after["incidents"] if not i["intact"]]
    print(table(["Incident", "Intact", "First bad entry", "Problem"], [[i["incident_id"], i["intact"], i["first_bad_update_no"], i["problem"]] for i in bad]) + "\n")
    _, detail = coordinator.call("GET", f"{R}/lab/chain/1")
    print(table(["Entry", "Note", "Content hash ok", "Link ok"], [[e["update_no"], e["note"], e["content_ok"], e["link_ok"]] for e in detail["entries"][:4]]) + "\n")
    admin.call("POST", f"{R}/lab/chain/restore", {"incident_id": 1, "update_no": 2, "note": original})
    _, healed = coordinator.call("GET", f"{R}/lab/chain")
    print(f"After restoring the original wording: **{healed['broken']} broken**.\n")

    # ---- 2 RLS
    print("## 2. Row-level security (migration 006)\n")
    _, rls = admin.call("GET", f"{R}/lab/rls")
    names = [s["person"]["account_type"] for s in rls["subjects"]]
    rows = []
    for index, probe in enumerate(rls["probes"]):
        base = rls["owner_baseline"].get(probe["label"], "-")
        rows.append([probe["label"], base] + [("refused " + o["sqlstate"]) if (o := s["outcomes"][index])["outcome"] == "refused" else o["outcome"] for s in rls["subjects"]])
    print(table(["Same SQL, run as", "App role (owner)"] + names, rows) + "\n")

    # ---- 3 isolation
    print("## 3. Isolation levels (migration 008)\n")
    _, matrix = coordinator.call("GET", f"{R}/lab/isolation/matrix")
    print(table(["Anomaly (naive code)"] + matrix["levels"], [[m["title"]] + [m["levels"][l] for l in matrix["levels"]] for m in matrix["matrix"]]) + "\n")
    _, skew = coordinator.call("POST", f"{R}/lab/isolation/run", {"scenario": "write_skew", "level": "SERIALIZABLE", "mode": "retry"})
    print(f"Write skew at SERIALIZABLE with a retry loop: {skew['verdict']}\n")
    steps = [[s["n"], s["session"], s["sql"] + (f" {s['params']}" if s["params"] else ""), json.dumps(s.get("result")) if s.get("result") is not None else (f"ERROR {s['error']['sqlstate']} {s['error']['name']}" if s.get("error") else "")] for s in skew["steps"]]
    print(table(["#", "Session", "Statement", "Result"], steps) + "\n")

    # ---- 4 reservations
    print("## 4. Exclusion-constraint reservations (migration 007)\n")
    first = coordinator.call("POST", f"{R}/lab/reservations", {"unit_id": 5, "purpose": "STANDBY", "starts_at": "2026-12-20T08:00+05:30", "ends_at": "2026-12-20T20:00+05:30"})
    clash = coordinator.call("POST", f"{R}/lab/reservations", {"unit_id": 5, "purpose": "TRAINING", "starts_at": "2026-12-20T19:00+05:30", "ends_at": "2026-12-21T02:00+05:30"})
    touch = coordinator.call("POST", f"{R}/lab/reservations", {"unit_id": 5, "purpose": "TRAINING", "starts_at": "2026-12-20T20:00+05:30", "ends_at": "2026-12-20T22:00+05:30"})
    print(table(["Request", "HTTP", "Outcome"], [["08:00-20:00 standby", first[0], "booked"], ["19:00-02:00 training (overlaps)", clash[0], f"{clash[1].get('code')}: {clash[1].get('error')} ({clash[1].get('constraint')}, {clash[1].get('sqlstate')}) rolled_back={clash[1]['db_trace']['rolled_back']}"], ["20:00-22:00 training (touches)", touch[0], "booked"]]) + "\n")
    for result in (first, touch):
        if result[0] == 201:
            coordinator.call("POST", f"{R}/lab/reservations/{result[1]['reservation']['id']}/cancel", {})

    # ---- 5 routing
    print("## 5. Routing inside PostgreSQL (migration 009)\n")
    s, loaded = admin.call("POST", f"{R}/lab/routing/load", {})
    print(f"Loaded into PostgreSQL: {loaded['loaded']} in {loaded['db_trace']['duration_ms']} ms.\n")
    body = {"from_lat": FIRE_STATION[0], "from_lon": FIRE_STATION[1], "to_lat": ASA_HOSPITAL[0], "to_lon": ASA_HOSPITAL[1]}
    _, clear = coordinator.call("POST", f"{R}/lab/routing/route", {**body, "hazards": []})
    mid = clear["database"]["path"][len(clear["database"]["path"]) // 2]
    _, blocked = coordinator.call("POST", f"{R}/lab/routing/route", {**body, "hazards": [{"lat": mid[0], "lon": mid[1]}]})
    rows = []
    for label, r in (("Vellore Fire station to A.S.A Hospital, clear", clear), ("same, road block mid-route", blocked)):
        for who in ("database", "python"):
            d = r[who]
            rows.append([label, who, f"{d['seconds'] / 60:.2f} min", f"{d['metres'] / 1000:.3f} km", d["segments"], d["nodes_explored"], d["closed_segments"], f"{d['runtime_ms']} ms", r["same_answer"]])
    print(table(["Case", "Engine", "Time", "Distance", "Segments", "Nodes expanded", "Closed", "Run time", "Same answer"], rows) + "\n")
    _, near = coordinator.call("POST", f"{R}/lab/routing/nearest", {"lat": 12.9231, "lon": 79.1389, "kind": "hospital", "k": 3})
    print(table(["Hospital", "Straight-line m", "Straight rank", "Drive min", "Drive rank"], [[c["name"], round(c["straight_line_m"]), c["straight_rank"], round(c["drive_seconds"] / 60, 2) if c["drive_seconds"] else None, c["drive_rank"]] for c in near["candidates"]]) + f"\n\nStraight-line winner differs from the by-road winner: **{near['straight_line_winner_differs']}**.\n")

    # ---- 6 optimiser
    print("## 6. Query optimiser (migration 010)\n")
    s, load = admin.call("POST", f"{R}/lab/query/load", {"rows": args.rows})
    print(f"`lab.fn_load_events({args.rows})`: {load['rows']:,} rows in {load['db_trace']['duration_ms'] / 1000:.1f} s (flat table and monthly-partitioned copy).\n")
    _, cat = coordinator.call("GET", f"{R}/lab/query/catalog")
    for exp in cat["experiments"]:
        out = []
        for variant in exp["variants"]:
            _, r = coordinator.call("POST", f"{R}/lab/query/run", {"experiment": exp["key"], "variant": variant["key"]})
            out.append([variant["label"], r["execution_ms"], ", ".join(r["scan_types"]), r["partitions_scanned"] or "", f"{r['buffers_hit']}/{r['buffers_read']}", r["index_bytes"] if r["index_bytes"] is not None else ""])
        print(f"**{exp['title']}**\n\n" + table(["Variant", "Execution ms", "Scan", "Partitions", "Buffers hit/read", "Index bytes"], out) + "\n")

    # ---- 8 analytics
    print("## 8. In-database analytics (migration 011)\n")
    _, analytics = coordinator.call("GET", f"{R}/lab/analytics?window=14&threshold=6")
    print(table(["Zone", "Day", "Incidents", "Trailing mean", "Std dev", "z-score"], [[x["zone"], x["day"], x["n"], x["trailing_mean"], x["trailing_sd"], x["z_score"]] for x in analytics["spikes"][:6]]) + "\n")
    print(table(["Zone", "Avg last 7 d", "Trend/day", "R2", "Next 7 days"], [[f["zone"], f["avg_last_7"], f["slope_per_day"], f["r_squared"], f["forecast_horizon_total"]] for f in analytics["forecast"][:5]]) + "\n")

    # ---- 9 privacy
    print("## 9. Privacy-safe export (migration 011)\n")
    rows = []
    for label, query in (("k=5, exact counts", "k=5"), ("k=5, epsilon=1", "k=5&epsilon=1&seed=0.25"), ("k=5, epsilon=0.2", "k=5&epsilon=0.2&seed=0.25"), ("k=40, exact counts", "k=40")):
        _, p = admin.call("GET", f"{R}/lab/privacy?{query}")
        sm = p["summary"]
        rows.append([label, sm["cells"], f"{sm['suppressed_cells']} ({sm['suppressed_percent']}%)", sm["true_total"], sm["released_total"], sm["mean_abs_error"]])
    print(table(["Release", "Cells", "Suppressed", "True total", "Released total", "Mean abs error / cell"], rows) + "\n")
    _, live = citizen.call("GET", f"{R}/lab/privacy?source=live&k=5")
    print(f"Live incidents (14) as a citizen with k=5: {live['summary']['suppressed_percent']}% of cells suppressed; the response carries no `true_count`.\n")

    # ---- 7 live push
    print("## 7. LISTEN / NOTIFY push (migration 012)\n")
    received: list[str] = []

    def listen():
        request = urllib.request.Request(args.base + R + "/stream", headers={"Authorization": f"Bearer {coordinator.token}"})
        try:
            with urllib.request.urlopen(request, timeout=20) as stream:
                deadline = time.time() + 12
                while time.time() < deadline:
                    line = stream.readline().decode().strip()
                    if line.startswith("data:"):
                        received.append(line[5:].strip())
        except Exception:        # the timeout ends the listener
            pass

    thread = threading.Thread(target=listen)
    thread.start()
    time.sleep(1.5)
    _, created = citizen.call("POST", f"{R}/incidents", {"title": "Live push demonstration", "incident_type": "OTHER", "location": "Demo lane"})
    coordinator.call("POST", f"{R}/incidents/{created['incident']['id']}/verify", {"zone_id": 1, "severity": "LOW"})
    thread.join()
    print("Messages received on the SSE stream (ids and statuses only):\n\n```\n" + "\n".join(received) + "\n```\n")

    admin.call("POST", f"{R}/demo/reset", {})
    print("The demonstration data was reset to the Review II baseline at the end of this run.")


if __name__ == "__main__":
    main()

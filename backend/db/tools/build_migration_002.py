"""Assemble backend/migrations/002_incident_response.sql from the Review II scripts.

The Review II tables, constraints, functions, procedures, triggers and view are copied
verbatim from backend/db/review2/. Only these mechanical changes are made:

* the objects are created in the PostgreSQL schema "response" (search_path = response, public);
* the Review II "users" table is not created: every users(id) reference resolves to public.users,
  which receives one additive column (a generated account_type) instead;
* CREATE TABLE / INDEX gain IF NOT EXISTS and CREATE TRIGGER becomes CREATE OR REPLACE TRIGGER,
  so that the migration can be applied twice;
* each function and procedure is pinned to the same search_path so it behaves identically whatever
  the caller's session setting is.

Run:  python -I db/tools/build_migration_002.py   (from the backend directory)
"""
from __future__ import annotations

import re
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[2]
SQL = BACKEND / "db" / "review2"
OUT = BACKEND / "migrations" / "002_incident_response.sql"

HEADER = """\
-- =====================================================================================
-- Migration 002: the Review II incident-response model inside the application database.
--
-- Generated by backend/db/tools/build_migration_002.py from backend/db/review2/*.sql.
-- Additive and idempotent: it can be applied twice, and also runs under psql when the
-- PostgreSQL container initialises a new volume (docker-entrypoint-initdb.d).
--
-- Placement: tables, constraints, functions, procedures, triggers and the view keep their
-- Review II names and live in schema "response". "users" is NOT duplicated: every users(id)
-- reference resolves to public.users, which gains a generated account_type column that maps
-- the application roles onto the four Review II account types.
-- =====================================================================================
SET client_min_messages = warning;

CREATE TABLE IF NOT EXISTS public.schema_migrations (
  version     TEXT PRIMARY KEY,
  description TEXT NOT NULL,
  applied_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---- public.users: one additive, derived column (decision D3 in docs/review3/PLAN.md) ----
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS account_type VARCHAR(15)
  GENERATED ALWAYS AS (CASE role WHEN 'admin' THEN 'ADMINISTRATOR'
                                 WHEN 'official' THEN 'COORDINATOR'
                                 WHEN 'responder' THEN 'UNIT_LEAD'
                                 ELSE 'CITIZEN' END) STORED;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conname = 'ck_users_account_type'
                    AND conrelid = 'public.users'::regclass) THEN
    ALTER TABLE public.users ADD CONSTRAINT ck_users_account_type
      CHECK (account_type IN ('CITIZEN', 'COORDINATOR', 'UNIT_LEAD', 'ADMINISTRATOR'));
  END IF;
END $$;

CREATE SCHEMA IF NOT EXISTS response;
COMMENT ON SCHEMA response IS 'Review II incident-response model (DMERS, BCSE302L)';
SET search_path = response, public;
"""

ADDITIONS = """\

-- =====================================================================================
-- Review III additions (rules that Review II left to the application; see PLAN.md, D7)
-- =====================================================================================

-- [R3-1] status transitions are legal only along the incident life cycle
CREATE OR REPLACE FUNCTION trg_fn_incident_transition_guard()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status AND NOT (
       (OLD.status = 'REPORTED'   AND NEW.status IN ('VERIFIED', 'REJECTED'))
    OR (OLD.status = 'VERIFIED'   AND NEW.status IN ('RESPONDING', 'RESOLVED', 'CLOSED'))
    OR (OLD.status = 'RESPONDING' AND NEW.status IN ('RESOLVED', 'CLOSED'))
    OR (OLD.status = 'RESOLVED'   AND NEW.status = 'CLOSED')) THEN
    RAISE EXCEPTION 'Illegal status change % -> % for incident %',
      OLD.status, NEW.status, OLD.id;
  END IF;
  RETURN NEW;
END $$;
ALTER FUNCTION trg_fn_incident_transition_guard() SET search_path = response, public;

CREATE OR REPLACE TRIGGER trg_incidents_transition_guard
BEFORE UPDATE OF status ON incidents
FOR EACH ROW EXECUTE FUNCTION trg_fn_incident_transition_guard();

-- [R3-2] only the lead of a unit records its dispatch progress; the unit is freed on completion
CREATE OR REPLACE PROCEDURE sp_update_dispatch(
    p_incident_id INTEGER, p_unit_id INTEGER,
    p_user_id INTEGER, p_new_status VARCHAR)
LANGUAGE plpgsql AS $$
DECLARE
  v_lead INTEGER;
  v_unit response_units.unit_name%TYPE;
  v_cur  dispatches.dispatch_status%TYPE;
BEGIN
  SELECT lead_user_id, unit_name INTO v_lead, v_unit
    FROM response_units WHERE id = p_unit_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Unit % does not exist', p_unit_id;
  END IF;
  IF v_lead IS DISTINCT FROM p_user_id THEN
    RAISE EXCEPTION 'User % is not the lead of unit % (%)',
      p_user_id, p_unit_id, v_unit;
  END IF;
  SELECT dispatch_status INTO v_cur FROM dispatches
   WHERE incident_id = p_incident_id AND unit_id = p_unit_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Unit % has no dispatch to incident %',
      p_unit_id, p_incident_id;
  END IF;
  IF NOT ((v_cur = 'ASSIGNED' AND p_new_status = 'EN_ROUTE')
       OR (v_cur = 'EN_ROUTE' AND p_new_status = 'ON_SCENE')
       OR (v_cur = 'ON_SCENE' AND p_new_status = 'COMPLETED')) THEN
    RAISE EXCEPTION 'Dispatch cannot move from % to %', v_cur, p_new_status;
  END IF;
  PERFORM set_config('dmers.actor_id', p_user_id::TEXT, true);
  IF p_new_status = 'EN_ROUTE' THEN
    UPDATE dispatches SET dispatch_status = 'EN_ROUTE'
     WHERE incident_id = p_incident_id AND unit_id = p_unit_id;
  ELSIF p_new_status = 'ON_SCENE' THEN
    UPDATE dispatches SET dispatch_status = 'ON_SCENE', arrived_at = now()
     WHERE incident_id = p_incident_id AND unit_id = p_unit_id;
  ELSE
    UPDATE dispatches SET dispatch_status = 'COMPLETED', cleared_at = now()
     WHERE incident_id = p_incident_id AND unit_id = p_unit_id;
    UPDATE response_units SET availability_status = 'AVAILABLE'
     WHERE id = p_unit_id;
  END IF;
  RAISE NOTICE 'Unit % (%) is now % at incident %',
    p_unit_id, v_unit, p_new_status, p_incident_id;
END $$;
ALTER PROCEDURE sp_update_dispatch(INTEGER, INTEGER, INTEGER, VARCHAR)
  SET search_path = response, public;

INSERT INTO public.schema_migrations (version, description)
VALUES ('002', 'Incident-response model (Review II) in schema response, users.account_type')
ON CONFLICT (version) DO NOTHING;

RESET search_path;
"""


def tables_without_users(schema_sql: str) -> str:
    """Return 01_schema.sql with the users table removed and DDL made idempotent."""
    schema_sql = schema_sql.replace("SET client_min_messages = warning;\n", "")
    parts = re.split(r"(?m)^(?=CREATE TABLE )", schema_sql)
    kept = [p for p in parts if not p.startswith("CREATE TABLE users ")]
    text = "".join(kept)
    text = re.sub(r"(?m)^CREATE TABLE (\w+)", r"CREATE TABLE IF NOT EXISTS \1", text)
    text = re.sub(r"(?m)^CREATE UNIQUE INDEX (\w+)", r"CREATE UNIQUE INDEX IF NOT EXISTS \1", text)
    text = re.sub(r"(?m)^CREATE INDEX (\w+)", r"CREATE INDEX IF NOT EXISTS \1", text)
    return text.strip() + "\n"


def plpgsql_with_pins(plpgsql_sql: str) -> str:
    """Keep every Review II routine verbatim and pin its search_path right after its definition."""
    text = plpgsql_sql.replace("SET client_min_messages = warning;\n", "")
    text = re.sub(r"(?m)^CREATE TRIGGER ", "CREATE OR REPLACE TRIGGER ", text)
    out, pos = [], 0
    for m in re.finditer(r"CREATE OR REPLACE (FUNCTION|PROCEDURE) (\w+)\((.*?)\)\s*(?:RETURNS|LANGUAGE)", text, re.S):
        kind, name = m.group(1), m.group(2)
        args = " ".join(m.group(3).split())
        types = [re.sub(r"\s+DEFAULT\s+.*$", "", a.strip(), flags=re.I).split()[-1] if a.strip() else "" for a in args.split(",")]
        # argument names are present, so take the type (last token before an optional DEFAULT)
        signature = ", ".join(t for t in types if t)
        end = text.index("END $$;", m.end()) + len("END $$;")
        out.append((end, f"\nALTER {kind} {name}({signature}) SET search_path = response, public;"))
    for end, extra in sorted(out, reverse=True):
        text = text[:end] + extra + text[end:]
    return text.strip() + "\n"


def view_q15(queries_sql: str) -> str:
    start = queries_sql.index("CREATE OR REPLACE VIEW v_zone_situation")
    end = queries_sql.index(";", start) + 1
    return queries_sql[start:end] + "\n"


def build() -> str:
    schema = tables_without_users((SQL / "01_schema.sql").read_text(encoding="utf-8"))
    plpgsql = plpgsql_with_pins((SQL / "02_plpgsql.sql").read_text(encoding="utf-8"))
    view = view_q15((SQL / "05_queries.sql").read_text(encoding="utf-8"))
    return (HEADER + "\n-- ---- Review II 01_schema.sql (users omitted: see header) ----\n" + schema
            + "\n-- ---- Review II 02_plpgsql.sql: 3 functions, 2 procedures, 5 triggers ----\n" + plpgsql
            + "\n-- ---- Review II 05_queries.sql, Q15: view over zones, units and fn_active_incidents ----\n" + view
            + ADDITIONS)


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
